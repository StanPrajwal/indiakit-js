import { fail, type ValidationResult } from "./types";

export interface UPIIdDetails {
  /** Part before "@", e.g. "merchant". */
  handle: string;
  /** Payment service provider handle after "@", e.g. "okhdfcbank", "ybl", "paytm". */
  provider: string;
}

// Handle: letters, digits, dot, hyphen, underscore. Provider: starts with a letter.
const VPA_RE = /^([a-zA-Z0-9._-]{2,256})@([a-zA-Z][a-zA-Z0-9.-]{1,63})$/;

/**
 * Validates a UPI ID (Virtual Payment Address), e.g. `merchant@okhdfcbank`.
 * Format only — whether the ID exists can only be checked through a PSP.
 */
export function validateUPIId(input: unknown): ValidationResult<UPIIdDetails> {
  const value = input === null || input === undefined ? "" : String(input).trim().toLowerCase();
  if (!value) return fail(value, "EMPTY", "UPI ID is required.");
  const m = VPA_RE.exec(value);
  if (!m) return fail(value, "INVALID_FORMAT", "UPI ID must look like name@bank (e.g. shop@okhdfcbank).");
  return { valid: true, value, details: { handle: m[1]!, provider: m[2]! } };
}

/** Convenience boolean form of {@link validateUPIId}. */
export function isValidUPIId(input: unknown): boolean {
  return validateUPIId(input).valid;
}

/** Parameters of a UPI payment link (NPCI UPI linking specification). */
export interface UPIPaymentParams {
  /** Payee UPI ID (`pa`). Required. */
  payeeAddress: string;
  /** Payee name (`pn`). Strongly recommended — some apps refuse links without it. */
  payeeName?: string;
  /** Amount in rupees (`am`). Omit to let the payer enter the amount. */
  amount?: number | string;
  /** Minimum amount (`mam`). */
  minimumAmount?: number | string;
  /** Transaction note shown to the payer (`tn`). */
  note?: string;
  /** Your order / transaction reference (`tr`). */
  transactionRef?: string;
  /** Transaction id (`tid`). Usually generated by the PSP — set only if your PSP asks for it. */
  transactionId?: string;
  /** Merchant category code (`mc`), 4 digits. */
  merchantCode?: string;
  /** Link to invoice / order (`url`). */
  url?: string;
  /** Currency (`cu`). Only "INR" is supported by UPI. */
  currency?: "INR";
}

export interface BuildUPILinkOptions {
  /** URI scheme. Default `upi`; some apps register their own (e.g. `phonepe`, `tez`, `paytmmp`). */
  scheme?: string;
}

/** @internal */
export function formatUPIAmount(amount: number | string): string {
  const n = typeof amount === "number" ? amount : Number(String(amount).replace(/[,₹\s]/g, ""));
  if (!Number.isFinite(n) || n <= 0) throw new RangeError("UPI amount must be a positive number.");
  if (n > 1e9) throw new RangeError("UPI amount is too large.");
  return n.toFixed(2);
}

function enc(v: string): string {
  // encodeURIComponent, but keep '@' readable in the VPA (accepted by all major UPI apps).
  return encodeURIComponent(v).replace(/%40/g, "@");
}

/**
 * Builds a UPI deep link such as
 * `upi://pay?pa=shop@okhdfcbank&pn=My%20Shop&am=499.00&cu=INR&tn=Order%20123`.
 *
 * Render the returned string as a QR code with any QR library, or use it as an
 * `<a href>` on mobile to open the payer's UPI app.
 */
export function buildUPILink(params: UPIPaymentParams, options: BuildUPILinkOptions = {}): string {
  const pa = validateUPIId(params.payeeAddress);
  if (!pa.valid) throw new TypeError(`Invalid payeeAddress: ${pa.message}`);

  const parts: Array<[string, string]> = [["pa", pa.value]];
  if (params.payeeName) parts.push(["pn", params.payeeName.trim()]);
  if (params.merchantCode) {
    if (!/^\d{4}$/.test(params.merchantCode)) throw new TypeError("merchantCode must be 4 digits.");
    parts.push(["mc", params.merchantCode]);
  }
  if (params.transactionId) parts.push(["tid", params.transactionId]);
  if (params.transactionRef) parts.push(["tr", params.transactionRef]);
  if (params.note) parts.push(["tn", params.note.slice(0, 80)]);
  if (params.amount !== undefined && params.amount !== "") parts.push(["am", formatUPIAmount(params.amount)]);
  if (params.minimumAmount !== undefined && params.minimumAmount !== "") {
    parts.push(["mam", formatUPIAmount(params.minimumAmount)]);
  }
  parts.push(["cu", params.currency ?? "INR"]);
  if (params.url) parts.push(["url", params.url]);

  const scheme = (options.scheme ?? "upi").replace(/:\/*$/, "");
  return `${scheme}://pay?${parts.map(([k, v]) => `${k}=${enc(v)}`).join("&")}`;
}

/**
 * Parses a UPI deep link (e.g. scanned from a QR code) back into its parameters.
 * Returns `null` if the string is not a UPI pay link.
 */
export function parseUPILink(link: string): (UPIPaymentParams & { raw: Record<string, string> }) | null {
  const m = /^([a-z][a-z0-9+.-]*):\/\/pay\?(.*)$/i.exec(link.trim());
  if (!m) return null;
  const raw: Record<string, string> = {};
  for (const pair of m[2]!.split("&")) {
    if (!pair) continue;
    const idx = pair.indexOf("=");
    const key = decodeURIComponent((idx < 0 ? pair : pair.slice(0, idx)).replace(/\+/g, " "));
    const val = idx < 0 ? "" : safeDecode(pair.slice(idx + 1));
    raw[key] = val;
  }
  if (!raw.pa) return null;
  const out: UPIPaymentParams & { raw: Record<string, string> } = { payeeAddress: raw.pa, raw };
  if (raw.pn) out.payeeName = raw.pn;
  if (raw.am) out.amount = raw.am;
  if (raw.mam) out.minimumAmount = raw.mam;
  if (raw.tn) out.note = raw.tn;
  if (raw.tr) out.transactionRef = raw.tr;
  if (raw.tid) out.transactionId = raw.tid;
  if (raw.mc) out.merchantCode = raw.mc;
  if (raw.url) out.url = raw.url;
  if (raw.cu === "INR") out.currency = "INR";
  return out;
}

function safeDecode(v: string): string {
  try {
    return decodeURIComponent(v.replace(/\+/g, " "));
  } catch {
    return v;
  }
}
